CREATE TABLE IF NOT EXISTS orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint REFERENCES users(id), email varchar(190) NOT NULL,
  status text NOT NULL DEFAULT 'pending_payment' CHECK (status IN ('pending_payment','processing_payment','paid','partially_fulfilled','fulfilled','cancelled','partially_refunded','refunded','disputed')),
