CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(190) NOT NULL UNIQUE,
  email_verified_at timestamptz,
  password_hash varchar(255) NOT NULL,
  last_login_at timestamptz,
  role text NOT NULL DEFAULT 'buyer' CHECK (role IN ('buyer','org_member','org_admin','platform_admin')),
  leaderboard_opt_in boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
  id varchar(128) PRIMARY KEY,
  user_id bigint REFERENCES users(id) ON DELETE CASCADE,
  csrf_token varchar(128) NOT NULL,
  data jsonb NOT NULL DEFAULT '{}'::jsonb,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS auth_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  purpose text NOT NULL CHECK (purpose IN ('email_verification','password_reset')),
  token_hash char(64) NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS auth_rate_limits (
  bucket_hash char(64) NOT NULL,
  action varchar(40) NOT NULL,
  attempts smallint NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  window_started_at timestamptz NOT NULL DEFAULT now(),
  blocked_until timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(bucket_hash,action)
);

CREATE TABLE IF NOT EXISTS organizations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('seed_bank','botanic_garden','nursery','shop','grower','collector')),
  name varchar(190) NOT NULL,
  slug varchar(190) NOT NULL UNIQUE,
  country varchar(100) NOT NULL,
  country_code char(2),
  region varchar(190),
  description text NOT NULL,
  specialties text,
  contact_url varchar(500),
  website_url varchar(500),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','info_requested')),
  seller_status text NOT NULL DEFAULT 'not_requested' CHECK (seller_status IN ('not_requested','onboarding','pending_review','active','suspended')),
  marketplace_enabled boolean NOT NULL DEFAULT false,
  stripe_account_id varchar(190) UNIQUE,
  stripe_charges_enabled boolean NOT NULL DEFAULT false,
  stripe_payouts_enabled boolean NOT NULL DEFAULT false,
  commission_bps integer NOT NULL DEFAULT 1000 CHECK (commission_bps BETWEEN 0 AND 5000),
  payout_policy text NOT NULL DEFAULT 'standard' CHECK (payout_policy IN ('standard','delivery_protected')),
  verified_at timestamptz,
  profile_updated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS organization_members (
