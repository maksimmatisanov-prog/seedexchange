CREATE TABLE IF NOT EXISTS products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations(id),
  external_source varchar(80), external_id varchar(190), source_updated_at timestamptz,
  source_sync_status text NOT NULL DEFAULT 'manual' CHECK (source_sync_status IN ('manual','current','stale','error','review_required')),
  purchase_mode text NOT NULL DEFAULT 'marketplace' CHECK (purchase_mode IN ('marketplace','external')),
  external_purchase_url varchar(1000), sku varchar(100) NOT NULL UNIQUE,
  name varchar(255) NOT NULL, botanical_name varchar(255), slug varchar(190) NOT NULL UNIQUE, category varchar(100),
  description text NOT NULL, origin_country varchar(100), packet_quantity varchar(120), germination_notes text, hardiness_zone varchar(80),
  price_cents bigint NOT NULL CHECK (price_cents >= 0), compare_at_price_cents bigint CHECK (compare_at_price_cents >= 0),
  currency char(3) NOT NULL DEFAULT 'EUR', stock_quantity integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  image_url varchar(1000), primary_media_id bigint REFERENCES media_assets(id),
  compliance_flag text NOT NULL DEFAULT 'none' CHECK (compliance_flag IN ('none','phytosanitary_required','restricted')),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending_review','active','rejected','sold_out','withdrawn')),
  publication_batch_id bigint, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(organization_id,external_source,external_id)
);
CREATE INDEX IF NOT EXISTS products_public_idx ON products(status,category,organization_id);

